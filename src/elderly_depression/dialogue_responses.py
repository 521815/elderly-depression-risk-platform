def get_fast_response(mode: str, intent: str) -> str | None:
    if mode == "companion":
        return COMPANION_RESPONSES.get(intent)
    return PROFESSIONAL_RESPONSES.get(intent)


def get_companion_archetype_response(intent: str, archetype: str) -> str | None:
    if archetype == "avoidant":
        return COMPANION_AVOIDANT_RESPONSE
    if archetype in {"moderate", "severe"}:
        return COMPANION_NEGATIVE_RESPONSES.get(intent)
    return None
